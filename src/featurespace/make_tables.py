"""The four v4 tables, generated from the JSONs rather than typed.

A number typed into LaTeX is a number that can go stale without anything
noticing; that is how 492 and 560 survived in a published README. Each table
here is written from the JSON that produced it, and each file carries the source
path in a comment so a reader can check the number against the file it came
from.

  tab_g1_distance.tex      G1: distance by condition, per benchmark and ruler
  tab_b_donor.tex          B: near fraction, W1 and dip, with the three regimes
  tab_c_flip.tex           C: standardised coefficient, AUC and the G3 verdict

Written to paper/tables/. The boundary that only the writing session edits
tables/ is crossed here at the author's explicit request, and the header of each
file says the table is generated and must not be hand-edited.
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
V4 = REPO / "docs/v4"
OUT = REPO / "docs/v4/tables"
OUT.mkdir(parents=True, exist_ok=True)

NICE = {"KVASIR": "Kvasir-VQA-x1", "SLAKE": "SLAKE", "VQARAD": "VQA-RAD",
        "PATHVQA": "PathVQA", "HEAL": "HEAL"}
RULER = {"medsiglip": "MedSigLIP", "dinov3": "DINOv3", "biomedclip": "BiomedCLIP",
         "dinov2": "DINOv2", "colorhist": "colour hist."}


def head(fname, source, caption, label):
    return ("%% GENERATED by src/featurespace/make_tables.py -- do not edit by hand.\n"
            "%% source: %s\n"
            "\\begin{table}[t]\n\\centering\n\\caption{%s}\n\\label{%s}\n"
            % (source, caption, label))


def tail():
    return "\\end{table}\n"


def w(fname, body):
    (OUT / fname).write_text(body)
    print("  gravado docs/v4/tables/%s" % fname)


# ---------------------------------------------------------------- table G1
g1 = json.loads((V4 / "g1_results.json").read_text())
fig = g1["figure3_relative_to_c0"]
rows = {}
for r in fig:
    if r["ruler"] != "medsiglip":
        continue
    rows.setdefault(r["benchmark"], {})[r["condition"]] = r
order = ["C0", "C1", "C2", "C5", "C6", "C3-25", "C3-50", "C3-75",
         "C4-25", "C4-50", "C4-75"]
E1 = json.loads((V4 / "analysis_e1.json").read_text())["cells"]
b = head("tab_g1_distance.tex", "docs/v4/g1_results.json",
         "Distance from each condition to the training bank, under MedSigLIP. "
         "$knn$ is the mean cosine distance to the ten nearest training images; "
         "the swaps C2, C5 and C6 carry the images of C0 permuted, so their "
         "equality with C0 is a construction check rather than a finding. "
         "C1 is a single distinct image, so its Fr\\'echet is undefined.",
         "tab:g1-distance")
b += "\\begin{tabular}{l" + "r" * len(rows) + "}\n\\toprule\n"
b += "Condition & " + " & ".join(NICE[x] for x in rows) + " \\\\\n\\midrule\n"
for c in order:
    cells = []
    for bench in rows:
        r = rows[bench].get(c)
        cells.append("--" if r is None else "%.4f" % r["knn_abs"])
    if all(x == "--" for x in cells):
        continue
    name = c + (" $^\\dagger$" if c == "C1" else "")
    b += "%s & %s \\\\\n" % (name, " & ".join(cells))
cells = []
for bench in rows:
    c = E1.get("%s|medsiglip" % bench)
    cells.append("--" if not c else "%.4f" % c["knn_c7"])
b += "C7 $^\\ddagger$ & %s \\\\\n" % " & ".join(cells)
above = [k for k, v in E1.items() if v.get("knn_c1") is not None
         and v["knn_c7"] > v["knn_c1"]]
b += ("\\bottomrule\n\\end{tabular}\n"
      "\\\\[2pt]\\footnotesize $^\\dagger$ single distinct image; "
      "Fr\\'echet undefined, $knn$ and sliced Wasserstein only. "
      "$^\\ddagger$ C7 permutes the 32$\\times$32 patches: every pixel kept, "
      "the arrangement destroyed. No model was run on it, so it has a distance "
      "and no VDD; its colour-histogram vectors are bit-identical to C0's. "
      "%s\n"
      % ("Under BiomedCLIP on VQA-RAD, C7 sits above C1." if any(
          k.startswith("VQARAD") and "biomedclip" in k for k in above) else ""))
w("tab_g1_distance.tex", b + tail())

# ----------------------------------------------------------------- table B
bj = json.loads((V4 / "analysis_b.json").read_text())["cells"]
dip = json.loads((V4 / "analysis_b_dip.json").read_text())["cells"]
br = json.loads((V4 / "bridge_v3_v4.json").read_text())["benchmarks"]
b = head("tab_b_donor.tex", "analysis_b.json, analysis_b_dip.json, bridge_v3_v4.json",
         "Analysis B, donor distance under MedSigLIP. Benchmarks with a domain "
         "label are tested by Wasserstein-1 between the near and far groups "
         "(1{,}000 label shuffles); those without are tested by Hartigan's dip "
         "on the distances, a weaker instrument whose negative result is not "
         "evidence of absence. HEAL is the negative control and must be "
         "unimodal.",
         "tab:b-donor")
# PathVQA is the farthest benchmark under all five rulers, unanimously; HEAL is
# the nearest under four of five and NOT under MedSigLIP, where it sits above
# Kvasir. The regime column says what the dip decides and the footnote says the
# rest, rather than asserting a position the primary ruler contradicts.
REGIME = {"PATHVQA": "unimodal, farthest$^{a}$",
          "HEAL": "unimodal$^{b}$"}
b += ("\\begin{tabular}{lrrrrl}\n\\toprule\n"
      "Benchmark & $\\bar d$ & near frac. & $W_1$ / dip & $p$ & Regime \\\\\n"
      "\\midrule\n")
for bench in ["KVASIR", "SLAKE", "VQARAD", "PATHVQA", "HEAL"]:
    dm = br[bench]["rulers"]["medsiglip"]["mean"]
    c = bj.get("%s|C2|medsiglip" % bench)
    d = dip.get("%s|medsiglip" % bench)
    if c and c.get("w1") is not None:
        stat, p = c["w1"], c["w1_p"]
        near = "%.3f" % c["near_fraction"]
        reg = "mixture, separates"
    else:
        stat, p = d["dip"], d["dip_p"]
        near = "--"
        # named by the dip, which tests shape; the position of a benchmark on
        # the d scale depends on the ruler and is not what the dip decides
        reg = REGIME[bench]
    b += "%s & %.3f & %s & %.4f & %.4f & %s \\\\\n" % (NICE[bench], dm, near, stat, p, reg)
b += ("\\bottomrule\n\\end{tabular}\n"
      "\\\\[2pt]\\footnotesize $^{a}$ farthest under all five rulers. "
      "$^{b}$ the rulers disagree on HEAL: it is the nearest benchmark under "
      "DINOv3, BiomedCLIP, DINOv2 and the colour histogram, and not under "
      "MedSigLIP, where it sits above Kvasir-VQA-x1. The dip tests shape, not "
      "position.\n")
w("tab_b_donor.tex", b + tail())

# ----------------------------------------------------------------- table C
cj = json.loads((V4 / "analysis_c.json").read_text())["cells"]
g3 = json.loads((V4 / "g3_results.json").read_text())
b = head("tab_c_flip.tex", "analysis_c.json, g3_results.json",
         "Analysis C, does donor distance predict that the answer changes. "
         "$\\beta_z$ is the logistic coefficient on $d$ standardised within "
         "benchmark and ruler; AUC is the probability that a flipped row has a "
         "larger $d$ than one that did not flip. Raw coefficients are not "
         "comparable across rulers because $d$ is not on the same scale. "
         "The colour histogram is the counterfactual and decides nothing.",
         "tab:c-flip")
b += ("\\begin{tabular}{l" + "rr" * 2 + "r}\n\\toprule\n"
      "& \\multicolumn{2}{c}{MedSigLIP} & \\multicolumn{2}{c}{colour hist.} & \\\\\n"
      "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
      "Benchmark & $\\beta_z$ & AUC & $\\beta_z$ & AUC & configurations \\\\\n\\midrule\n")
for bench in ["KVASIR", "SLAKE", "VQARAD"]:
    vals = []
    for r in ("medsiglip", "colorhist"):
        v = [cj[k] for k in cj if k.startswith("%s|" % bench) and k.endswith("|%s" % r)
             and not cj[k].get("reference_only") and "auc" in cj[k]]
        vals += [sum(x["coef_z"] for x in v) / len(v), sum(x["auc"] for x in v) / len(v)]
    npass = sum(1 for k, x in g3["cells"].items()
                if k.startswith("%s|" % bench) and x["seeds_pass"])
    b += ("%s & %+.3f & %.3f & %+.3f & %.3f & %d/5 \\\\\n"
          % (NICE[bench], vals[0], vals[1], vals[2], vals[3], npass))
b += ("\\bottomrule\n\\end{tabular}\n"
      "\\\\[2pt]\\footnotesize G3 passes with %d of 15 cells; a cell counts only "
      "when all three seeds have a positive coefficient whose interval excludes "
      "zero.\n" % g3["cells_passing"])
w("tab_c_flip.tex", b + tail())

# The table of v3 corrections was generated here until 2026-09-20. It left the
# paper: it corrects a version no reader has seen, and the two counts the text
# still needs are in the sentence itself.

# ----------------------------------------------------------- table E2 (HN)
E2 = json.loads((V4 / "analysis_e2.json").read_text())["benchmarks"]
b = head("tab_e2_hn.tex", "analysis_e2.json",
         "What CORAL's hard negative selects, measured with no model. The "
         "restriction $\\mathrm{label}(x_j) \\neq y_i$ can only exclude an image "
         "whose every question carries $y_i$, so the share of pool images "
         "holding two or more distinct labels is the ceiling on what it can "
         "filter; on SLAKE that ceiling is zero. $\\phi$ is the share of "
         "verifiable items whose gold answer actually changes. C2 and C5 are "
         "this paper's swaps, on the same quantities. PathVQA has no C5 and no "
         "pHash cache entry, both marked absent rather than filled.",
         "tab:e2-hn")
b += ("\\begin{tabular}{llrrrrr}\n\\toprule\n"
      "Benchmark & Donor map & $|V|$ & $\\phi$ & $\\bar d$ & cos & "
      "filter ceiling \\\\\n\\midrule\n")
for bench, nice in (("KVASIR", "Kvasir-VQA-x1"), ("SLAKE", "SLAKE"),
                    ("PATHVQA", "PathVQA")):
    r = E2[bench]
    ceil = r["pool"]["filter_ceiling"]
    first = True
    for enc, lab in (("biomedclip", "HN, BiomedCLIP"), ("clipL14", "HN, CLIP-L/14")):
        h = r["hard_negative"][enc]
        b += ("%s & %s & %d & %.3f & %.3f & %.3f & %s \\\\\n"
              % (nice if first else "", lab, h["V_HN"], h["phi_HN"],
                 h["d_medsiglip_mean"], h["cosine_mean"],
                 "%.1f\\%%" % (100 * ceil) if first else ""))
        first = False
    for cond in ("C2", "C5"):          # not `w`: that name is the writer above
        q = r["reference"].get(cond)
        if q:
            b += ("& %s & %d & %.3f & %.3f & -- & \\\\\n"
                  % (cond, q["V"], q["phi"], q["d_medsiglip_mean"]))
    cr = r.get("correct_restriction", {}).get("biomedclip")
    if cr:
        b += ("& correct restriction & %d & 1.000 & %.3f & %.3f & \\\\\n"
              % (cr["items_with_donor"], cr["d_medsiglip_mean"], cr["cosine_mean"]))
    b += "\\midrule\n"
b = b[:-len("\\midrule\n")]
b += ("\\bottomrule\n\\end{tabular}\n"
      "\\\\[2pt]\\footnotesize The correct restriction asks that the donor's "
      "reference for $q_i$ differ from $y_i$, which makes $\\phi$ one by "
      "construction; the row reports how many items still find a donor under it. "
      "VQA-RAD and PathVQA are excluded, as pre-registered.\n")
w("tab_e2_hn.tex", b + tail())
print("\n  cinco tabelas em paper/tables/")
