"""The number sheet: every figure the text may cite, with its source and commit.

Nothing here is typed. Each line is read out of the JSON that produced it, and
the commit is the one that last touched that JSON, taken from git. A number the
paper cites and this file cannot produce is a number with no provenance, and
should not be cited.

The order of the sections follows the paper, not the order the analyses ran.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
V4 = REPO / "docs/v4"
OUT = V4 / "numbers_v4.md"

_cache = {}


def commit(rel):
    if rel not in _cache:
        r = subprocess.run(["git", "log", "-1", "--format=%h", "--", rel],
                           cwd=REPO, capture_output=True, text=True)
        _cache[rel] = r.stdout.strip() or "sem commit"
    return _cache[rel]


def J(name):
    return json.loads((V4 / name).read_text())


L = []


def sec(title):
    L.append("\n## %s\n" % title)


def line(what, value, src):
    L.append("- **%s** — `%s`  \n  <sub>%s · `%s`</sub>"
             % (what, value, src, commit("docs/v4/" + src)))


def note(text):
    L.append("\n%s\n" % text)


L.append("# Number sheet — VISAPP v4\n")
L.append("Every number the text may cite, with the JSON it comes from and the "
         "commit that wrote it. Generated by `src/featurespace/make_numbers.py`; a "
         "number the paper cites and this file cannot produce has no "
         "provenance and should not be cited.\n")

